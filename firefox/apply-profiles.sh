#!/usr/bin/env bash
# apply-profiles.sh - aplica la config de firefox/ a los perfiles "Personal"
# (navegador diario) y "Aplicaciones" (solo PWA). Solo Linux, idempotente.
#
#   1. user.js en cada perfil (Aplicaciones suma user-apps.js).
#   2. Excepciones de cookies (cookie-exceptions.txt) en permissions.sqlite.
#   3. Zoom por defecto en content-prefs.sqlite.
#   4. Override del .desktop de Firefox con -profile fijo al perfil Personal.
#   5. Symlink ~/.local/bin/firefox-personal -> open-personal.sh ($BROWSER).
#
# Los perfiles se buscan por nombre en "Profile Groups/*.sqlite"; si no existen
# hay que crearlos una vez desde el selector de Firefox, con esos nombres.
#
# Uso: apply-profiles.sh [--dry-run] [--remove]
# Salida: 0 todo aplicado | 3 algo quedo sin aplicar | 2 uso incorrecto.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FF_DIR="${FIREFOX_DIR:-$HOME/.config/mozilla/firefox}"
PERSONAL_NAME="${FIREFOX_PROFILE_PERSONAL:-Personal}"
APPS_NAME="${FIREFOX_PROFILE_APPS:-Aplicaciones}"
ZOOM="${FIREFOX_ZOOM:-0.9}"
SYSTEM_DESKTOP="${FIREFOX_SYSTEM_DESKTOP:-/usr/share/applications/org.mozilla.firefox.desktop}"
DESKTOP_DEST="$HOME/.local/share/applications/org.mozilla.firefox.desktop"
LAUNCHER_DEST="$HOME/.local/bin/firefox-personal"
JS_MARK="// dotfiles: generated by firefox/apply-profiles.sh - edit the repo, not this file"
JS_MARK_PREFIX="// dotfiles: "
DESKTOP_MARK="X-Dotfiles-Generated=firefox"
ZOOM_KEY="browser.content.full-zoom"

MODE=apply
DRY_RUN=false
SKIPPED=0

for arg in "$@"; do
    case "$arg" in
        --dry-run) DRY_RUN=true ;;
        --remove)  MODE=remove ;;
        -h|--help) sed -n '2,15p' "${BASH_SOURCE[0]}"; exit 0 ;;
        *) echo "[firefox] argumento desconocido: $arg" >&2; exit 2 ;;
    esac
done

info()   { printf '[firefox] %s\n' "$*"; }
dry_note() { printf '[firefox][DryRun] %s\n' "$*"; }
# Algo quedo sin aplicar: avisa y lo cuenta para el exit 3 (no aborta el resto).
skip() { printf '[firefox][WARN] %s\n' "$*" >&2; SKIPPED=$((SKIPPED + 1)); }

# Escapa comillas simples para interpolar en SQL.
sq() { printf '%s' "${1//\'/\'\'}"; }

# profile_path <name> - imprime la ruta absoluta del perfil o nada.
profile_path() {
    local name db dir
    name="$(sq "$1")"
    for db in "$FF_DIR/Profile Groups"/*.sqlite; do
        [[ -f "$db" ]] || continue
        dir="$(sqlite3 -readonly "$db" "SELECT path FROM Profiles WHERE name='$name' LIMIT 1;" 2>/dev/null)" || continue
        if [[ -n "$dir" ]]; then
            [[ "$dir" == /* ]] || dir="$FF_DIR/$dir"
            printf '%s\n' "$dir"
            return 0
        fi
    done
    return 0
}

# profile_in_use <dir> - 0 si hay un Firefox vivo con ese perfil (symlink 'lock' -> ip:+PID).
profile_in_use() {
    local lock="$1/lock" dest pid
    [[ -L "$lock" ]] || return 1
    dest="$(readlink "$lock")"
    pid="${dest##*+}"
    [[ "$pid" =~ ^[0-9]+$ ]] && kill -0 "$pid" 2>/dev/null
}

write_userjs() {
    local dir="$1" label="$2"; shift 2
    local dest="$dir/user.js" tmp f
    tmp="$(mktemp)"
    { printf '%s\n\n' "$JS_MARK"; for f in "$@"; do cat "$f"; printf '\n'; done; } > "$tmp"
    if [[ -f "$dest" ]] && cmp -s "$tmp" "$dest"; then
        info "$label: user.js sin cambios"
        rm -f "$tmp"
        return 0
    fi
    if [[ "$DRY_RUN" == true ]]; then
        dry_note "$label: escribiria $dest"
        rm -f "$tmp"
        return 0
    fi
    # Un user.js ajeno (sin nuestra marca) no se pisa en silencio.
    if [[ -f "$dest" ]] && ! grep -qF "$JS_MARK_PREFIX" "$dest"; then
        mv "$dest" "$dest.anterior"
        info "$label: user.js propio guardado como user.js.anterior"
    fi
    mv "$tmp" "$dest"
    chmod 644 "$dest"
    info "$label: user.js escrito"
}

load_cookie_exceptions() {
    local dir="$1" label="$2" db="$1/permissions.sqlite" list_file="$HERE/cookie-exceptions.txt"
    local now_ms origin esc sql=""
    [[ -f "$list_file" ]] || { skip "$label: falta $list_file"; return 0; }
    if [[ ! -f "$db" ]]; then
        skip "$label: aun no existe permissions.sqlite (abri el perfil una vez y re-corre)"
        return 0
    fi
    if [[ "$DRY_RUN" == true ]]; then
        dry_note "$label: cargaria las excepciones de cookies de $(basename "$list_file")"
        return 0
    fi
    if profile_in_use "$dir"; then
        skip "$label: Firefox esta abierto, no toco permissions.sqlite (cerralo y re-corre)"
        return 0
    fi
    now_ms=$(( $(date +%s) * 1000 ))
    while IFS= read -r origin; do
        [[ -z "$origin" || "$origin" == \#* ]] && continue
        esc="$(sq "$origin")"
        # persist-data-on-shutdown es el que respeta el borrado al cerrar; cookie es el permiso clasico.
        for kind in cookie persist-data-on-shutdown; do
            sql+="INSERT INTO moz_perms(origin,type,permission,expireType,expireTime,modificationTime) SELECT '$esc','$kind',1,0,0,$now_ms WHERE NOT EXISTS (SELECT 1 FROM moz_perms WHERE origin='$esc' AND type='$kind');"
        done
    done < "$list_file"
    if sqlite3 -cmd ".timeout 3000" "$db" "BEGIN; $sql COMMIT;" 2>/dev/null; then
        info "$label: excepciones de cookies cargadas"
    else
        skip "$label: no pude escribir permissions.sqlite (bloqueada)"
    fi
}

set_zoom() {
    local dir="$1" label="$2" db="$1/content-prefs.sqlite"
    local id="(SELECT id FROM settings WHERE name='$ZOOM_KEY')"
    if [[ ! -f "$db" ]]; then
        skip "$label: aun no existe content-prefs.sqlite (abri el perfil una vez y re-corre)"
        return 0
    fi
    if [[ "$DRY_RUN" == true ]]; then
        dry_note "$label: fijaria el zoom global en $ZOOM"
        return 0
    fi
    if profile_in_use "$dir"; then
        skip "$label: Firefox esta abierto, no toco content-prefs.sqlite (cerralo y re-corre)"
        return 0
    fi
    if sqlite3 -cmd ".timeout 3000" "$db" "
        INSERT INTO settings(name) SELECT '$ZOOM_KEY' WHERE NOT EXISTS (SELECT 1 FROM settings WHERE name='$ZOOM_KEY');
        UPDATE prefs SET value=$ZOOM WHERE groupID IS NULL AND settingID=$id;
        INSERT INTO prefs(groupID,settingID,value,timestamp) SELECT NULL,$id,$ZOOM,CAST(strftime('%s','now') AS INTEGER)
            WHERE NOT EXISTS (SELECT 1 FROM prefs WHERE groupID IS NULL AND settingID=$id);" 2>/dev/null; then
        info "$label: zoom global en $ZOOM"
    else
        skip "$label: no pude escribir content-prefs.sqlite (bloqueada)"
    fi
}

generate_desktop() {
    local dir="$1" tmp
    if [[ ! -f "$SYSTEM_DESKTOP" ]]; then
        skip "no encuentro $SYSTEM_DESKTOP (Firefox no instalado por rpm?)"
        return 0
    fi
    if [[ "$DRY_RUN" == true ]]; then
        dry_note "escribiria $DESKTOP_DEST con -profile $dir"
        return 0
    fi
    tmp="$(mktemp)"
    # El perfil va fijo en cada Exec (salvo el gestor de perfiles, que debe
    # seguir abriendo el selector).
    sed -e "/--ProfileManager/!s|^Exec=firefox |Exec=firefox -profile $dir |" \
        -e "0,/^\[Desktop Entry\]/s//[Desktop Entry]\n$DESKTOP_MARK/" \
        "$SYSTEM_DESKTOP" > "$tmp"
    if [[ -f "$DESKTOP_DEST" ]] && cmp -s "$tmp" "$DESKTOP_DEST"; then
        info ".desktop sin cambios"
        rm -f "$tmp"
        return 0
    fi
    mkdir -p "$(dirname "$DESKTOP_DEST")"
    mv "$tmp" "$DESKTOP_DEST"
    chmod 644 "$DESKTOP_DEST"
    command -v update-desktop-database &>/dev/null \
        && update-desktop-database "$(dirname "$DESKTOP_DEST")" &>/dev/null || true
    info ".desktop con perfil fijo escrito ($DESKTOP_DEST)"
}

link_launcher() {
    if [[ "$DRY_RUN" == true ]]; then
        dry_note "enlazaria $LAUNCHER_DEST -> $HERE/open-personal.sh"
        return 0
    fi
    mkdir -p "$(dirname "$LAUNCHER_DEST")"
    ln -sfn "$HERE/open-personal.sh" "$LAUNCHER_DEST"
    info "launcher enlazado ($LAUNCHER_DEST)"
}

remove_all() {
    local dir
    for dir in "$@"; do
        [[ -n "$dir" && -f "$dir/user.js" ]] || continue
        if grep -qF "$JS_MARK_PREFIX" "$dir/user.js"; then
            if [[ "$DRY_RUN" == true ]]; then dry_note "quitaria $dir/user.js"; else rm -f "$dir/user.js"; info "user.js removido de $(basename "$dir")"; fi
        fi
    done
    if [[ -f "$DESKTOP_DEST" ]] && grep -qF "$DESKTOP_MARK" "$DESKTOP_DEST"; then
        if [[ "$DRY_RUN" == true ]]; then dry_note "quitaria $DESKTOP_DEST"; else rm -f "$DESKTOP_DEST"; info ".desktop propio removido"; fi
    fi
    if [[ -L "$LAUNCHER_DEST" && "$(readlink "$LAUNCHER_DEST")" == "$HERE/open-personal.sh" ]]; then
        if [[ "$DRY_RUN" == true ]]; then dry_note "quitaria $LAUNCHER_DEST"; else rm -f "$LAUNCHER_DEST"; info "launcher removido"; fi
    fi
}

# ------------------------------------------------------------------------------

command -v sqlite3 &>/dev/null || { echo "[firefox][WARN] falta sqlite3: no se puede resolver los perfiles" >&2; exit 3; }
[[ -d "$FF_DIR" ]] || { echo "[firefox][WARN] no existe $FF_DIR (Firefox nunca se abrio?)" >&2; exit 3; }

PERSONAL_DIR="$(profile_path "$PERSONAL_NAME")"
APPS_DIR="$(profile_path "$APPS_NAME")"

if [[ "$MODE" == remove ]]; then
    remove_all "$PERSONAL_DIR" "$APPS_DIR"
    exit 0
fi

if [[ -n "$PERSONAL_DIR" && -d "$PERSONAL_DIR" ]]; then
    write_userjs "$PERSONAL_DIR" "$PERSONAL_NAME" "$HERE/user.js"
    load_cookie_exceptions  "$PERSONAL_DIR" "$PERSONAL_NAME"
    set_zoom      "$PERSONAL_DIR" "$PERSONAL_NAME"
    generate_desktop "$PERSONAL_DIR"
    link_launcher
else
    skip "no encuentro el perfil '$PERSONAL_NAME': crealo desde el selector de perfiles de Firefox (nombre exacto) y re-corre"
fi

if [[ -n "$APPS_DIR" && -d "$APPS_DIR" ]]; then
    write_userjs "$APPS_DIR" "$APPS_NAME" "$HERE/user.js" "$HERE/user-apps.js"
    load_cookie_exceptions  "$APPS_DIR" "$APPS_NAME"
    set_zoom      "$APPS_DIR" "$APPS_NAME"
else
    skip "no encuentro el perfil '$APPS_NAME': crealo desde el selector de perfiles de Firefox (nombre exacto) y re-corre"
fi

[[ "$SKIPPED" -eq 0 ]] || exit 3
exit 0
